import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import assert from 'node:assert/strict';

// Offline projection of a pinned upstream catalog; never loads QQ or an account.
const commit = '26d7533e0f5800fdff865ab2f2ad7692917e1076';
const blob = 'ba937ea96f315235c80e34039d5c039f9b8e2d3c';
const args = process.argv.slice(2);
const check = args.includes('--check');
const sourceIndex = args.indexOf('--source');
if (args.some((arg, i) => arg !== '--check' && arg !== '--source' && !(sourceIndex >= 0 && i === sourceIndex + 1))) throw new Error('Use --check and/or --source PATH');
if (sourceIndex >= 0 && !args[sourceIndex + 1]) throw new Error('--source requires PATH');
const source = sourceIndex < 0 ? new URL('../.local/research/qq-face-config-pinned.json', import.meta.url) : args[sourceIndex + 1];
const bytes = await readFile(source);
const actualBlob = createHash('sha1').update(`blob ${bytes.length}\0`).update(bytes).digest('hex');
assert.equal(actualBlob, blob, 'Catalog must match the exact upstream Git blob');
const rows = JSON.parse(bytes.toString('utf8')).sysface;
assert.equal(rows.length, 329);
const ids = new Set();
const projected = rows.map(row => {
  assert.equal(typeof row.QSid, 'string');
  assert.match(row.QSid, /^(0|[1-9]\d*)$/);
  const id = Number(row.QSid);
  assert.ok(Number.isSafeInteger(id) && id >= 0 && !ids.has(id), 'IDs must be unique safe integers');
  ids.add(id);
  assert.equal(typeof row.QDes, 'string');
  if (row.AniStickerType === undefined) {
    assert.equal(row.AniStickerPackId, undefined);
    assert.equal(row.AniStickerId, undefined);
    return [id, row.QDes];
  }
  assert.ok(Number.isInteger(row.AniStickerType) && row.AniStickerType >= 0);
  assert.equal(typeof row.AniStickerPackId, 'string');
  assert.equal(typeof row.AniStickerId, 'string');
  return [id, row.QDes, row.AniStickerType, row.AniStickerPackId, row.AniStickerId];
}).sort((a, b) => a[0] - b[0]);
const output = `// Generated by scripts/generate-qq-faces.mjs. Do not edit by hand.
// Source: NapNeko/NapCatQQ ${commit}
// packages/napcat-core/external/face_config.json; Git blob ${blob}
// Only outbound ID/name/animation metadata is retained; no UI assets.
type FaceRow = readonly [id: number, text: string, stickerType?: number, packId?: string, stickerId?: string];
export const qqFaceRows: readonly FaceRow[] = [
${projected.map(row => '  ' + JSON.stringify(row) + ',').join('\n')}
];
`;
const target = new URL('../src/qq-faces.ts', import.meta.url);
if (check) assert.equal(await readFile(target, 'utf8'), output, 'Regenerate the catalog');
else await writeFile(target, output);
console.log(JSON.stringify({ sourceBlob: blob, entries: projected.length, bytes: Buffer.byteLength(output), target: fileURLToPath(target), check }));
